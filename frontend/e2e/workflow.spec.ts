import { test, expect } from '@playwright/test'

test('咨询聊天、执行轨迹、反馈及刷新恢复', async ({ page }) => {
  await page.goto('/')
  await page.getByPlaceholder('说说你的学习目标，例如：我想转行学 Python').fill('我想学Python')
  await page.getByRole('button', { name: '发送 ↑' }).click()
  await expect(page.getByText('先了解您的学习目标。再结合基础规划学习路径。')).toBeVisible()
  await expect(page.getByText('recall_playbook', { exact: true }).first()).toBeVisible()
  await page.getByPlaceholder('可选反馈原因').fill('希望更简短')
  await page.getByRole('button', { name: '👎' }).click()
  await expect(page.getByText('已记录反馈')).toBeVisible()
  await page.reload()
  await expect(page.getByText('先了解您的学习目标。再结合基础规划学习路径。')).toBeVisible()
  await page.getByRole('link', { name: '进入管理后台 ↗' }).click()
  await expect(page.getByRole('heading', { name: '工单管理', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '返回咨询平台 ↗' }).click()
  await expect(page.getByRole('heading', { name: '编程学习咨询' })).toBeVisible()
})

test('训练样本新增、审核、编辑重新审核和删除', async ({ page }) => {
  page.on('dialog', d => d.accept())
  await page.goto('/admin.html')
  await page.getByRole('button', { name: '训练样本', exact: true }).click()
  await page.getByLabel('学员问题').fill('浏览器验收问题')
  await page.getByLabel('标注答案').fill('先了解需求。')
  await page.getByLabel('这么回答的原因').fill('确认基础与目标')
  await page.getByRole('button', { name: '保存并提交审核' }).click()
  const row = page.locator('article').filter({ hasText: '浏览器验收问题' })
  await expect(row).toContainText('pending')
  await row.getByRole('button', { name: '审核通过' }).click()
  await expect(row).toContainText('approved')
  await row.getByRole('button', { name: '编辑', exact: true }).click()
  await page.getByLabel('标注答案').fill('先了解基础和目标。')
  await page.getByRole('button', { name: '保存并提交审核' }).click()
  await expect(row).toContainText('pending')
  await row.getByRole('button', { name: '删除', exact: true }).click()
  await expect(row).toHaveCount(0)
})

test('知识审核、Prompt 发布和版本历史', async ({ page }) => {
  page.on('dialog', d => d.accept())
  await page.goto('/admin.html')
  await page.getByRole('button', { name: '知识审核与检索', exact: true }).click()
  await page.getByLabel('问题', { exact: true }).fill('Python 变量是什么')
  await page.getByLabel('事实答案').fill('变量用于保存值。')
  await page.getByLabel('可核验来源').fill('浏览器验收模拟教研文档')
  await page.getByRole('button', { name: '提交审核', exact: true }).click()
  const row = page.locator('article').filter({ hasText: 'Python 变量是什么' })
  await row.getByRole('button', { name: '确认入库' }).click()
  await expect(row).toContainText('approved')
  await page.getByRole('button', { name: '系统提示词', exact: true }).click()
  const editor = page.getByLabel('基础系统提示词', { exact: true })
  await expect(editor).not.toBeEmpty()
  await editor.fill((await editor.inputValue()) + '\n优先回应重点。')
  await page.getByRole('button', { name: '校验、真实冒烟并发布' }).click()
  await expect(page.getByText('v2 已发布，当前会话下一轮回答生效。')).toBeVisible()
  await expect(page.getByLabel('完整系统提示词预览')).toHaveValue(/优先回应重点/)
  await page.screenshot({ path: 'test-results/admin.png', fullPage: true })
})
